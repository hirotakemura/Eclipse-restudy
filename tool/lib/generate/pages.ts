/**
 * KOBO — 生成するページの決定
 *
 * ヒアリング結果の「サイトの役割」（集客／選別／採用／信用構築）に応じて出し分ける。
 * 綺麗なサイトを作るのではなく、**足りていない引き合いを取るサイト**を作るため（docs/06 ブロック2）。
 */

import type { Project } from "../schema.ts";

export interface PageSpec {
  /** ファイル名になる */
  slug: string;
  title: string;
  /** このページの役割。プロンプトに入る */
  purpose: string;
  /** 構成の指示 */
  outline: string;
  /** 事例ページのとき、何番目の事例か */
  caseIndex?: number;
}

export function decidePages(project: Project): PageSpec[] {
  const goals = new Set(project.inquiry?.goals ?? []);
  const pages: PageSpec[] = [];

  pages.push({
    slug: "index",
    title: "トップページ",
    purpose:
      "初めて来た調達担当者が、10秒で「この会社は自分の案件を受けられるか」を判断できるようにする。",
    outline:
      "①一文で何ができる会社かを言い切る見出し（どんな加工を、どんな条件で）" +
      "②対応できる材質・加工法・ロット・納期を、箇条書きで即座に示す" +
      "③他社が断った案件を受けている事実を、具体例で1つ" +
      "④加工事例へのリンク ⑤問い合わせ（電話番号とメールアドレスを必ず併記する）",
  });

  pages.push({
    slug: "company",
    title: "会社概要",
    purpose: "発注前に会社の実在と規模を確認する人向け。読み物ではなく、確認のための表。",
    outline: "会社概要の表（社名・代表・創業・資本金・従業員数・所在地・連絡先）と、沿革。",
  });

  pages.push({
    slug: "strengths",
    title: "強み・技術",
    purpose:
      "「なぜこの会社なのか」に答える。**サイトで最も差がつくページ。** " +
      "取材の追い質問で引き出した、顧客自身が言語化できていなかった強みを、ここで言葉にする。",
    outline:
      "①他社が断った案件を受けられる理由を、工程レベルで説明する" +
      "②顧客が繰り返し言う褒め言葉を、その理由とともに書く" +
      "③追い質問で判明したこと（治具の内製など）を、独立した見出しで扱う" +
      "④誇張しない。事実だけで十分に強い。",
  });

  pages.push({
    slug: "capability",
    title: "対応可能範囲",
    purpose:
      "**SEOの本体。** 調達担当者は「材質 × 加工法 × 条件」で検索する。" +
      "この表があるかどうかで、検索に出るかが決まる。",
    outline:
      "対応材質・加工法・対応サイズ・精度・ロット・納期・認証・稼働体制を表にする。" +
      "**データにない項目は {{要確認}} と書き、決して推測で埋めない。**",
  });

  pages.push({
    slug: "equipment",
    title: "設備一覧",
    purpose:
      "**設備の型番そのものが検索される。** 「この設備を持つ会社を探している」という検索が実在する。",
    outline:
      "メーカー・型番・台数の表。型番が未確認のものは {{要確認}} と明記する。" +
      "**型番を推測で書かない。** 間違った型番は検索で拾われず、信用も落とす。",
  });

  (project.cases ?? []).forEach((c, i) => {
    pages.push({
      slug: `case-${i + 1}`,
      title: `加工事例：${c.title || `事例${i + 1}`}`,
      purpose:
        "**最も読まれ、最も問い合わせに繋がるページ。** " +
        "調達担当者は「自分の案件と似た仕事をやったことがあるか」だけを見ている。",
      outline:
        "①どんな業界の、どんな部品か（社名は絶対に書かない）" +
        "②相談されたときの困りごと。他社に断られた経緯があれば必ず書く" +
        "③どう解決したか。工程の工夫を具体的に" +
        "④結果。数値がデータにない場合は {{要確認}} とし、作り話をしない。",
      caseIndex: i,
    });
  });

  if (goals.has("採用")) {
    pages.push({
      slug: "recruit",
      title: "採用情報",
      purpose:
        "この会社の場合、**採用が売上の上限を決めている。** " +
        "利益率の高い仕事を増やしたくても、対応できる人がいなければ受けられない。",
      outline:
        "①どんな仕事か（求職者は仕事の中身を知りたい。福利厚生は後）" +
        "②どんな技術が身につくか ③募集職種と条件 ④応募方法。" +
        "データにない条件を書かない。",
    });
  }

  if (goals.has("採用") || goals.has("信用構築")) {
    pages.push({
      slug: "message",
      title: "代表挨拶",
      purpose:
        "会社の方向性を、代表の言葉で示す。**採用と、取引前の信用確認の両方で読まれる。**",
      outline:
        "取材で語られた5年後のビジョンと、社員に伝えたいことを軸にする。" +
        "**取材で出た言葉をそのまま活かす。** 一般的な社長挨拶に薄めない。",
    });
  }

  pages.push({
    slug: "contact",
    title: "お問い合わせ",
    purpose: "問い合わせの経路を複数用意する。",
    outline:
      "**電話番号とメールアドレスを必ず併記する**（D-060）。フォームだけに依存させない。" +
      "中小製造業の担当者は電話を使う。相談時に用意してもらえると早い情報（図面・材質・数量・希望納期）も案内する。",
  });

  return pages;
}
