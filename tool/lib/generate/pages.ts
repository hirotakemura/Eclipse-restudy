/**
 * KOBO — 生成するページの決定
 *
 * ヒアリング結果の「サイトの役割」（集客／選別／採用／信用構築）に応じて出し分ける。
 * 綺麗なサイトを作るのではなく、**足りていない引き合いを取るサイト**を作るため（docs/06 ブロック2）。
 *
 * **表と一覧は生成しない（D-095）。**
 * 会社概要・対応可能範囲・設備一覧・お問い合わせは、聞き取ったデータをテンプレートが
 * そのまま出す。生成を通せば、通した分だけ捏造の余地が生まれる。事実の羅列に創作は要らない。
 * ここで作るのは散文だけ。そのぶん生成するページ数も費用も減る。
 */

import type { Project } from "../schema.ts";

export interface PageSpec {
  /** ファイル名になる */
  slug: string;
  title: string;
  /** このページの役割。プロンプトに入る */
  purpose: string;
  /** 構成の指示 */
  outline: string;
  /** 事例ページのとき、何番目の事例か */
  caseIndex?: number;
}


/**
 * その事例で、原稿を書けるだけの材料があるか（D-254）。
 *
 * **無い材料は、AIに渡しても出てこない。** 出てくるのは `{{要確認}}` で埋まった原稿である。
 * 実測（松原精機）では、4件の事例のうち2件が「どう解決したか」を聞けておらず、
 * 生成された `case-2.md` `case-3.md` は**ほぼ全行が `{{要確認}}`** だった。
 * それでも1ページぶんの費用はかかり、人間はそれを読まされる。
 *
 * **事例ページの中心は「どう解決したか」**（工程の工夫）である。
 * ここが無い事例は、読み手の「自分の案件と似た仕事をやったことがあるか」に答えられない。
 * 相談の内容も無ければ、なおさら書きようがない。
 *
 * この判定は `sanitizeProject` を通した後のデータに対して行う。
 * 「`{{要確認}}` だけが入っている欄」は、その時点で空欄になっている。
 *
 * **ページを作らないだけで、事例そのものは消えない。**
 * 事例の一覧と個別ページはテンプレートが聞き取ったデータから出す。
 * 散文が無いページになるだけで、載っている事実は変わらない。
 */
export function hasCaseMaterial(c: { challenge?: string; solution?: string; partDescription?: string }): boolean {
  const has = (v?: string) => typeof v === "string" && v.trim().length > 0;
  return has(c.solution) && (has(c.challenge) || has(c.partDescription));
}

export function decidePages(project: Project): PageSpec[] {
  const goals = new Set(project.inquiry?.goals ?? []);
  if ((project as any).formSet === "general") return generalPages(project, goals);
  const pages: PageSpec[] = [];

  pages.push({
    slug: "index",
    title: "トップページ",
    purpose:
      "初めて来た調達担当者が、10秒で「この会社は自分の案件を受けられるか」を判断できるようにする。",
    /**
     * **構成（下に示す）がすでに出しているものは、書かない**（D-193）。
     * 材質・ロット・納期は最初の画面と札が出す。他社様が断った案件も帯が出す。
     * 電話番号と問い合わせ先はテンプレートが全ページに置く（D-060／D-175）。
     */
    outline:
      "**3〜6行の短い文章。** 見出しは付けても付けなくてよい。" +
      "①この会社が引き受けている仕事の輪郭を、一文で言い切る" +
      "②その仕事を、なぜこの会社が引き受けられるのかを一言で" +
      "③読み手（発注先を探している調達担当者・設計者）が、次にどこを見ればよいかが分かる流れにする。" +
      "**箇条書きで条件を並べない。表を書かない。電話番号やメールアドレスを書かない。**",
  });

  pages.push({
    slug: "strengths",
    title: "強み・技術",
    purpose:
      "「なぜこの会社なのか」に答える。**サイトで最も差がつくページ。** " +
      "取材の追い質問で引き出した、顧客自身が言語化できていなかった強みを、ここで言葉にする。",
    /**
     * 聞き取った文章そのものは、テンプレートが帯と札で出す（D-193）。
     * ここで書くのは**それらをつなぐ理由**。
     */
    outline:
      "**4〜8行。** 断られた案件の記録も、工程の工夫も、褒め言葉も、" +
      "テンプレートが聞き取ったまま出します。**同じ内容を書き直さないでください。**" +
      "書くのは、それらに共通している一本の筋です。" +
      "①なぜこの会社は、他社が断る仕事を引き受けられるのか（工程・判断・経験のどれが効いているか）" +
      "②その力がどこから来ているのか。**誇張しない。事実だけで十分に強い。**",
  });

  pages.push({
    slug: "capability",
    title: "対応可能範囲",
    purpose:
      "**SEOの本体。** 調達担当者は「材質 × 加工法 × 条件」で検索する。" +
      "この表があるかどうかで、検索に出るかが決まる。",
    outline:
      "**表も、条件の大きな数字も、材質の札も、テンプレートが出します。表を書かないこと。**" +
      "ここで書くのは3〜5行だけ。" +
      "①どういう仕事を得意としていて、どこまで相談に乗れるのか" +
      "②**表の外側の話を書く。** 材質名やロット数を文章で並べ直さない。" +
      "「一覧に無い条件でも可否だけは答える」という姿勢が伝わればよい。",
  });

  pages.push({
    slug: "equipment",
    title: "設備一覧",
    purpose:
      "**設備の型番そのものが検索される。** 「この設備を持つ会社を探している」という検索が実在する。",
    outline:
      "**一覧表も、型番の分かる設備の札も、テンプレートが出します。表を書かないこと。**" +
      "ここで書くのは2〜4行だけ。" +
      "どういう加工に使う設備が揃っているのかを、**設備名を並べずに**一文で示す。" +
      "**型番を推測で書かない。**",
  });

  (project.cases ?? []).forEach((c, i) => {
    if (!hasCaseMaterial(c)) return;
    pages.push({
      slug: `case-${i + 1}`,
      title: `加工事例：${c.title || `事例${i + 1}`}`,
      purpose:
        "**最も読まれ、最も問い合わせに繋がるページ。** " +
        "調達担当者は「自分の案件と似た仕事をやったことがあるか」だけを見ている。",
      outline:
        "①どんな業界の、どんな部品か（社名は絶対に書かない）" +
        "②相談されたときの困りごと。他社に断られた経緯があれば必ず書く" +
        "③どう解決したか。工程の工夫を具体的に" +
        "④結果。数値がデータにない場合は {{要確認}} とし、作り話をしない。",
      caseIndex: i,
    });
  });

  if (goals.has("採用")) {
    pages.push({
      slug: "recruit",
      title: "採用情報",
      purpose:
        "この会社の場合、**採用が売上の上限を決めている。** " +
        "利益率の高い仕事を増やしたくても、対応できる人がいなければ受けられない。",
      outline:
        "①どんな仕事か（求職者は仕事の中身を知りたい。福利厚生は後）" +
        "②どんな技術が身につくか。" +
        "**募集要項（雇用形態・給与・休日・社会保険など）はテンプレートが表で出します**（D-171）。" +
        "条件を文章で書き直さないでください。**データにない条件を書かない。**",
    });
  }

  if (goals.has("採用") || goals.has("信用構築")) {
    pages.push({
      slug: "message",
      title: "代表挨拶",
      purpose:
        "会社の方向性を、代表の言葉で示す。**採用と、取引前の信用確認の両方で読まれる。**",
      outline:
        "取材で語られた5年後のビジョンと、社員に伝えたいことを軸にする。" +
        "**取材で出た言葉をそのまま活かす。** 一般的な社長挨拶に薄めない。",
    });
  }

  return pages;
}

/**
 * 汎用ベーシック（198,000円）で作るページ。
 *
 * **ページ数を増やさない。** 30分の取材で取れる材料しかないので、
 * 薄いページを10枚作るより、要る4枚を厚く書くほうが問い合わせに繋がる。
 * 会社概要・お問い合わせ・実績の一覧は、テンプレートがデータから出す（D-095）。
 */
function generalPages(project: Project, goals: Set<string>): PageSpec[] {
  const pages: PageSpec[] = [];

  pages.push({
    slug: "index",
    title: "トップページ",
    purpose:
      "初めて来た人が、10秒で「自分の用は足りるか」を判断できるようにする。" +
      "見ているのは、何を・いくらで・どこまで来てくれるのか、の3つ。",
    /** 電話番号と問い合わせ先は、テンプレートが全ページに置く（D-060／D-175） */
    outline:
      "**3〜6行の短い文章。**" +
      "①一文で何をしている会社かを言い切る（業種の名前ではなく、客の困りごとの言葉で）" +
      "②選ばれている理由を1つだけ、具体で。" +
      "**対応エリア・取り扱い・料金の表はテンプレートが出します。箇条書きで並べ直さない。**" +
      "**電話番号やメールアドレスを書かない。**",
  });

  if ((project as any).general?.offerings?.length) {
    pages.push({
      slug: "services",
      title: "サービス・料金",
      purpose:
        "**サイトを見た人が知りたいのは「何を、いくらで、誰に」の3つ。** " +
        "ここが書かれていないサイトは、業種を問わず問い合わせに繋がらない。",
      outline:
        "**各サービスの名前・内容・料金はテンプレートがデータから出す。表を書かないこと。**" +
        "ここで書くのは、その前に置く3〜5行の説明文だけ。" +
        "初めての人が読んで、自分の用が足りるかどうかが分かる言い方にする。",
    });
  }

  pages.push({
    slug: "strengths",
    title: "選ばれている理由",
    purpose:
      "同業がいくらでもいる中で、なぜこの会社なのかに答える。**最も差がつくページ。**",
    outline:
      "**4〜8行。** 聞き取った言葉そのもの（選ばれている理由・お客様の言葉）は" +
      "テンプレートが帯と札で出します。**同じ内容を書き直さないでください。**" +
      "書くのは、それらに共通している一本の筋。" +
      "①同業と比べてどこが違うのか ②その違いがどこから来ているのか。" +
      "**誇張しない。事実だけで十分に強い。**",
  });

  if ((project.cases ?? []).length) {
    pages.push({
      slug: "cases",
      title: "実績",
      purpose: "「自分と似た困りごとを解決したことがあるか」を見せる。",
      outline:
        "**各実績の見出し・相談内容・対応・結果はテンプレートがデータから出す。個別に書き起こさないこと。**" +
        "ここで書くのは、一覧の前に置く2〜4行の説明文だけ。社名は絶対に書かない。",
    });
  }

  if (goals.has("採用")) {
    pages.push({
      slug: "recruit",
      title: "採用情報",
      purpose: "求職者向け。仕事の中身を先に、条件は後に。",
      outline: "①どんな仕事か ②募集職種と条件 ③応募方法。データにない条件を書かない。",
    });
  }

  return pages;
}
